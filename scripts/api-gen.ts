/**
 * bun run api:gen    regenerate src/api/schema.gen.ts from the backend's openapi.json
 * bun run api:check  same, but fail when the committed file differs (CI drift check)
 *
 * Source, first match wins:
 *   OPENAPI_SOURCE=<url or file path>   (a local backend checkout, a release asset, staging)
 *   default: https://api-staging.gezcez.com/openapi.json
 */
import openapiTS, { astToString } from "openapi-typescript"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const OUT = path.join(ROOT, "src/api/schema.gen.ts")
const check = process.argv.includes("--check")
const source = process.env.OPENAPI_SOURCE ?? "https://api-staging.gezcez.com/openapi.json"

async function load(): Promise<string> {
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source)
    if (!res.ok) throw new Error(`GET ${source} -> ${res.status}`)
    return await res.text()
  }
  return fs.readFileSync(path.resolve(source), "utf8")
}

const json = await load()
const ast = await openapiTS(JSON.parse(json), { alphabetize: true, exportType: false })
const header = [
  "/**",
  " * GENERATED by `bun run api:gen` from the backend's openapi.json. Do not edit by hand.",
  " * Endpoints the backend does not publish yet are typed in ./schema.manual.ts.",
  " */",
  "",
].join("\n")
const output = header + astToString(ast)

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
  if (current !== output) {
    console.error(`src/api/schema.gen.ts is out of date with ${source}. Run \`bun run api:gen\`.`)
    process.exit(1)
  }
  console.log("schema.gen.ts is up to date")
} else {
  fs.writeFileSync(OUT, output)
  console.log(`wrote ${path.relative(ROOT, OUT)} from ${source}`)
}
